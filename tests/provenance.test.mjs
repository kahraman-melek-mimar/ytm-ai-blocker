import test from 'node:test';
import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile} from 'node:fs/promises';
const scope = vm.createContext({});
vm.runInContext(await readFile(new URL('../extension/provenance.js', import.meta.url), 'utf8'), scope);
const {inspect, label} = scope.YTMProvenance;
test('provider declaration is text evidence, never a verified watermark', () => {
  const result = inspect({description: 'This song was created with Suno.'});
  assert.equal(result.evidence[0].kind, 'declaration');
  assert.equal(result.credentials, 'unavailable'); assert.equal(result.watermark, 'not-verified');
});
test('mentions, negation, unrelated studio text are not production proof', () => {
  for (const description of ['Suno tutorial', 'Not made with Suno', 'Made without Udio', 'Suno kullanılmadı']) {
    assert.equal(inspect({description}).evidence[0].kind, 'mention');
  }
  assert.equal(inspect({title: 'Studio recording'}).evidence.length, 0);
});
test('platform disclosure remains distinct from acoustic score and music provenance', () => {
  const result = inspect({disclosure: 'Made with AI'});
  assert.equal(result.evidence[0].kind, 'platform-disclosure');
  assert.match(label(result), /ses.görsel ayrımı belirsiz/);
  assert.equal('probability' in result, false);
});
test('missing labels do not imply human-made music', () => {
  assert.match(label(inspect({})), /beyanı bulunamadı/);
  assert.equal(inspect({description: 'Auto-generated by YouTube. Provided by DistroKid.'}).evidence.length, 0);
});
